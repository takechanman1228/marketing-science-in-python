"""Common dataset loaders. Encodes the data-folder policy:

  - **raw**:       external datasets under ``data/raw/`` (gitignored; fetched on
                   demand or placed manually — see ``data/raw/README.md``)
  - **generated**: derived-from-raw and synthetic data under ``data/generated/``
                   (gitignored by default; canonical/expensive outputs committed)

For raw datasets where automatic fetching is impractical or licensing is
unclear, readers must place files manually — see ``data/raw/README.md``.
"""
from __future__ import annotations

import shutil
from pathlib import Path

import pandas as pd

from msbook.paths import DATA_DIR


# =============================================================================
# Generated tier — derived/synthetic data committed in repo (data/generated/)
# =============================================================================

def load_mmm_synthetic() -> pd.DataFrame:
    """Bundled synthetic MMM dataset used by Part 6 chapters.

    Loaded from ``data/generated/part6/sec6.2-mmm/mmm_synthetic_data.csv``.
    Generated by the script alongside the dataset (see directory README).
    """
    path = DATA_DIR / "generated" / "part6" / "sec6.2-mmm" / "mmm_synthetic_data.csv"
    if not path.exists():
        raise FileNotFoundError(
            f"Expected synthetic file at {path}. "
            "Run notebooks/part6-media-optimization/mmm_data_generation.py to regenerate."
        )
    return pd.read_csv(path)


